#!/usr/bin/env python3
"""Builds תקין 106 (the WhatsApp edition) in the 106/ folder from the main תקין עירוני files.

The two editions share one source: index.html decides which edition it is from its address
(/takin/106/ → תקין 106). This script copies it and fixes the paths of the shared icons.
Run it after every change to index.html or sw.js:   python3 build-106.py
"""
import json, pathlib, re

root = pathlib.Path(__file__).resolve().parent
out = root / "106"
out.mkdir(exist_ok=True)

# page: same code, icons live one folder up
html = (root / "index.html").read_text(encoding="utf-8")
for name in ("icon.svg", "icon-192.png", "icon-512.png"):
    html = html.replace(f'href="{name}"', f'href="../{name}"')
html = html.replace("<title>תקין עירוני</title>", "<title>תקין 106</title>")
(out / "index.html").write_text(html, encoding="utf-8")

# offline worker: own cache name, shared icons from the parent folder
sw = (root / "sw.js").read_text(encoding="utf-8")
sw = sw.replace('"takin-v', '"takin106-v')
sw = re.sub(r'"(icon[^"]*\.(?:svg|png))"', r'"../\1"', sw)
sw = sw.replace("// תקין – service worker", "// תקין 106 – service worker (generated by build-106.py)")
(out / "sw.js").write_text(sw, encoding="utf-8")

# install details shown on the phone's home screen
m = json.loads((root / "manifest.webmanifest").read_text(encoding="utf-8"))
m["name"] = "תקין 106 – דיווח מפגעים בוואטסאפ"
m["short_name"] = "תקין 106"
m["description"] = "רואים מפגע? מצלמים ושולחים בוואטסאפ למוקד 106."
for ic in m.get("icons", []):
    ic["src"] = "../" + ic["src"]
(out / "manifest.webmanifest").write_text(json.dumps(m, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

print("built 106/ (index.html, sw.js, manifest.webmanifest)")
